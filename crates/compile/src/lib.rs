//! The spec compiler: a checked document in, a bundle out. The `data` kit
//! compiles to JSON Schema 2020-12, OpenAPI 3.1 and AsyncAPI 3, the `flow`
//! kit to Serverless Workflow and Node-RED, the `infra` kit to one OpenTofu
//! root module per environment (each a [`target`]); every document, typed
//! or not, gets a build brief (`AGENTS.md`, `tasks/tasks.json`) describing
//! what is left for an agent to build.
//!
//! **Determinism.** The same document and rhizo version give the same bytes:
//! output follows document order, nothing reads the clock, the environment
//! or the network, and `manifest.json` records every file with its sha256.

mod brief;
mod data;
mod flow;
mod infra;
mod target;

pub use brief::{AGENTS, TASKS};
pub use infra::{ADOPTED_FILE, environment_dir};

use std::collections::BTreeMap;

use rhizo_core::Document;
use rhizo_kit::{Finding, Kits};
use sha2::{Digest, Sha256};

/// Bundle-relative path (forward slashes) to file.
pub type Files = BTreeMap<String, OutFile>;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct OutFile {
    pub contents: String,
    /// Ids of the nodes this file derives from, for traceability.
    pub nodes: Vec<String>,
}

#[derive(Debug)]
pub struct Bundle {
    pub files: Files,
    /// Kit findings that did not stop compilation.
    pub warnings: Vec<Finding>,
}

pub const MANIFEST: &str = "manifest.json";

/// Where the parts of a merged project were written, so the brief keeps
/// each edge with the diagram it was drawn in.
#[derive(Clone, Debug, Default)]
pub struct Origins {
    /// File names, relative to the project root.
    pub files: Vec<String>,
    /// File of each `doc.edges[i]`.
    pub edge_file: Vec<usize>,
    /// File each node was defined in.
    pub node_file: std::collections::HashMap<rhizo_core::NodeId, usize>,
}

/// Checks `doc` against its kits and, if nothing is an error, compiles it.
/// `source_name` (a file name, not a path) and `source` go into the
/// manifest and the generated-file headers.
pub fn compile(doc: &Document, kits: &Kits, source_name: &str, source: &str) -> Result<Bundle, Vec<Finding>> {
    compile_with(doc, kits, source_name, source, None)
}

/// [`compile`] for a merged project, knowing which file each part came from.
pub fn compile_with(
    doc: &Document,
    kits: &Kits,
    source_name: &str,
    source: &str,
    origins: Option<&Origins>,
) -> Result<Bundle, Vec<Finding>> {
    let (errors, warnings): (Vec<_>, Vec<_>) =
        rhizo_kit::check(doc, kits).into_iter().partition(|f| f.diagnostic.is_error());
    if !errors.is_empty() {
        return Err(errors);
    }
    let header = format!(
        "@generated by rhizo {} from {}. Do not edit: change the diagram and recompile.",
        VERSION,
        one_line(source_name)
    );
    let mut files = Files::new();
    let cx = target::Cx { doc, source_name, header: &header };
    let used = kits.used_by(doc);
    for t in target::TARGETS.iter().filter(|t| used.iter().any(|k| k.name == t.kit())) {
        t.emit(&cx, &mut files)?;
    }
    // Every document gets a brief: what is left to build, for an agent.
    brief::emit(doc, kits, &header, source_name, origins, &mut files);
    // Every path comes from the compilers, some from ids the author chose:
    // refuse anything that could leave the bundle folder.
    // Two outputs with one name (also case-insensitively, for macOS and
    // Windows) would overwrite each other.
    let mut seen = std::collections::HashMap::new();
    for p in files.keys() {
        if let Some(other) = seen.insert(p.to_lowercase(), p) {
            let d = rhizo_lang::Diagnostic::error(
                format!("`{other}` and `{p}` would be the same file; rename one of the nodes they come from"),
                None,
            );
            return Err(vec![Finding { subject: rhizo_kit::Subject::Document, diagnostic: d }]);
        }
    }
    if let Some(bad) = files.keys().find(|p| !safe_path(p)) {
        let d = rhizo_lang::Diagnostic::error(
            format!("refusing to write `{bad}`: not a plain path inside the bundle"),
            None,
        );
        return Err(vec![Finding { subject: rhizo_kit::Subject::Document, diagnostic: d }]);
    }
    let manifest = manifest(source_name, source, &files);
    files.insert(MANIFEST.into(), OutFile { contents: manifest, nodes: Vec::new() });
    Ok(Bundle { files, warnings })
}

const VERSION: &str = env!("CARGO_PKG_VERSION");

pub fn sha256(bytes: &[u8]) -> String {
    Sha256::digest(bytes).iter().map(|b| format!("{b:02x}")).collect()
}

fn manifest(source_name: &str, source: &str, files: &Files) -> String {
    let list: Vec<serde_json::Value> = files
        .iter()
        .map(|(path, f)| {
            serde_json::json!({
                "path": path,
                "sha256": sha256(f.contents.as_bytes()),
                "owner": "generated",
                "nodes": f.nodes,
            })
        })
        .collect();
    let m = serde_json::json!({
        "generator": format!("rhizo {VERSION}"),
        "source": { "name": source_name, "sha256": sha256(source.as_bytes()) },
        "files": list,
    });
    json(&m)
}

/// Paths and hashes of the generated files a manifest lists. Paths that
/// could escape the bundle folder are left out.
pub fn manifest_files(manifest: &str) -> Vec<(String, String)> {
    let Ok(m) = serde_json::from_str::<serde_json::Value>(manifest) else { return Vec::new() };
    let Some(files) = m.get("files").and_then(|f| f.as_array()) else { return Vec::new() };
    files
        .iter()
        .filter(|f| f.get("owner").and_then(|o| o.as_str()) == Some("generated"))
        .filter_map(|f| Some((f.get("path")?.as_str()?.to_string(), f.get("sha256")?.as_str()?.to_string())))
        .filter(|(p, _)| safe_path(p))
        .collect()
}

/// Relative, forward slashes, every segment made of `[A-Za-z0-9._-]` and
/// not starting with a dot: nothing can climb out of the bundle folder,
/// name a drive or hide a file. The one hidden file allowed is OpenTofu's
/// `.terraform.lock.hcl`, which an imported environment carries.
pub fn safe_path(p: &str) -> bool {
    !p.is_empty()
        && p.split('/').all(|s| {
            !s.is_empty()
                && (!s.starts_with('.') || s == ".terraform.lock.hcl")
                && s.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'))
        })
}

/// A file name for an id: characters outside `[A-Za-z0-9._-]` become `-`,
/// and a leading dot gets a `_` in front (`../x` → `_..-x`, `model:order`
/// → `model-order`).
pub(crate) fn file_stem(id: &str) -> String {
    let s: String =
        id.chars().map(|c| if c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-') { c } else { '-' }).collect();
    if s.is_empty() || s.starts_with('.') { format!("_{s}") } else { s }
}

/// `s` on one line: control characters (line breaks, `\r`, Unicode line
/// separators) become spaces. For author text written into comments of
/// generated code, where a line break would turn text into code.
pub(crate) fn one_line(s: &str) -> String {
    s.chars().map(|c| if c.is_control() || matches!(c, '\u{2028}' | '\u{2029}' | '\u{85}') { ' ' } else { c }).collect()
}

/// Pretty JSON with a trailing newline.
pub(crate) fn json(v: &serde_json::Value) -> String {
    serde_json::to_string_pretty(v).expect("JSON values serialize") + "\n"
}

