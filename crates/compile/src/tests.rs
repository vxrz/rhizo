#[test]
fn manifest_paths_cannot_escape() {
    for bad in ["", "/etc/passwd", "../x", "a/../b", "a//b", "./a", "a\\b", "C:/x", ".hidden", "a/b:c", "a b"] {
        assert!(!safe_path(bad), "{bad}");
    }
    assert!(safe_path("specs/schemas/a.schema.json"));
    let m = r#"{"files":[{"path":"../evil","sha256":"x","owner":"generated"},{"path":"ok.json","sha256":"y","owner":"generated"},{"path":"mine.md","sha256":"z","owner":"scaffold"}]}"#;
    assert_eq!(manifest_files(m), [("ok.json".to_string(), "y".to_string())]);
}

