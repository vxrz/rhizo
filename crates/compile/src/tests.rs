use pretty_assertions::assert_eq;

use super::*;

const EXAMPLE: &str = include_str!("../../../examples/playground/11-data-model.rhizo");

fn build(src: &str) -> Result<Bundle, Vec<String>> {
    let loaded = rhizo_lang::load(src, rhizo_lang::Syntax::Kdl);
    assert!(!loaded.has_errors(), "{:?}", loaded.diagnostics);
    compile(&loaded.document, &Kits::builtin(), "shop.rhizo", src)
        .map_err(|fs| fs.into_iter().map(|f| f.diagnostic.message).collect())
}

fn parsed(b: &Bundle, path: &str) -> serde_json::Value {
    let text = &b.files.get(path).unwrap_or_else(|| panic!("no {path} in {:?}", b.files.keys())).contents;
    if path.ends_with(".yaml") { serde_yaml_ng::from_str(text).unwrap() } else { serde_json::from_str(text).unwrap() }
}

#[test]
fn bundle_layout_and_determinism() {
    let a = build(EXAMPLE).unwrap();
    let paths: Vec<&str> = a.files.keys().map(String::as_str).collect();
    assert_eq!(
        paths,
        [
            "AGENTS.md",
            "manifest.json",
            "specs/asyncapi.yaml",
            "specs/schemas/customer.schema.json",
            "specs/schemas/order.schema.json",
            "specs/shop-api.openapi.yaml",
            "tasks/tasks.json",
        ]
    );
    let b = build(EXAMPLE).unwrap();
    assert_eq!(a.files, b.files);
    // The manifest lists every other file with its hash.
    let m = parsed(&a, MANIFEST);
    let listed = manifest_files(&a.files[MANIFEST].contents);
    assert_eq!(listed.len(), 6);
    for (path, hash) in listed {
        assert_eq!(hash, sha256(a.files[&path].contents.as_bytes()));
    }
    assert_eq!(m["source"]["sha256"], sha256(EXAMPLE.as_bytes()));
}

#[test]
fn entity_schemas_are_valid_and_strict() {
    let b = build(EXAMPLE).unwrap();
    let order = parsed(&b, "specs/schemas/order.schema.json");
    assert_eq!(order["required"], serde_json::json!(["id", "total"]));
    assert_eq!(
        order["properties"]["total"],
        serde_json::json!({ "type": "number", "minimum": 0, "x-rhizo-node": "order-total" })
    );
    assert_eq!(order["x-rhizo-node"], "order");
    assert_eq!(order["properties"]["placed_at"]["format"], "date-time");
    assert_eq!(
        order["properties"]["customer"],
        serde_json::json!({ "$ref": "customer.schema.json", "description": "placed by" })
    );
    let customer = parsed(&b, "specs/schemas/customer.schema.json");
    assert_eq!(customer["properties"]["email"]["x-rhizo-pii"], "personal");

    // Meta-valid 2020-12, and it accepts and rejects what it should.
    let v = jsonschema::draft202012::new(&customer).unwrap();
    assert!(v.is_valid(&serde_json::json!({ "id": "c1", "email": "a@b.c" })));
    assert!(!v.is_valid(&serde_json::json!({ "id": "c1" })), "email is required");
    assert!(!v.is_valid(&serde_json::json!({ "id": "c1", "email": "a@b.c", "extra": 1 })));
}

#[test]
fn openapi_document() {
    let b = build(EXAMPLE).unwrap();
    let text = &b.files["specs/shop-api.openapi.yaml"].contents;
    assert!(text.starts_with("# @generated by rhizo"));
    let api = parsed(&b, "specs/shop-api.openapi.yaml");
    assert_eq!(api["openapi"], "3.1.0");
    assert_eq!(
        api["info"],
        serde_json::json!({
            "title": "Shop API",
            "version": "1.0.0",
            "license": { "name": "Apache-2.0", "identifier": "Apache-2.0" }
        })
    );
    assert_eq!(api["servers"][0]["url"], "https://api.example.com");
    let list = &api["paths"]["/orders"]["get"];
    assert_eq!(list["operationId"], "listOrders");
    assert_eq!(list["x-rhizo-node"], "list-orders");
    assert_eq!(
        list["responses"]["200"]["content"]["application/json"]["schema"],
        serde_json::json!({ "type": "array", "items": { "$ref": "#/components/schemas/Order" } })
    );
    let place = &api["paths"]["/orders"]["post"];
    assert_eq!(place["requestBody"]["content"]["application/json"]["schema"]["$ref"], "#/components/schemas/Order");
    assert_eq!(place["responses"]["201"]["description"], "Created");
    // Order refers to Customer, so both are components; refs are rewritten.
    let schemas = api["components"]["schemas"].as_object().unwrap();
    assert_eq!(schemas.keys().collect::<Vec<_>>(), ["Customer", "Order", "Problem"]);
    assert_eq!(
        list["responses"]["4XX"]["content"]["application/problem+json"]["schema"]["$ref"],
        "#/components/schemas/Problem"
    );
    assert_eq!(schemas["Order"]["properties"]["customer"]["$ref"], "#/components/schemas/Customer");
    assert_eq!(api["security"], serde_json::json!([{ "oauth2": [] }]));
}

#[test]
fn enums_path_params_and_status_labels() {
    let src = r#"rhizo version=2
use data version="0.1"
node "Ticket" id=ticket type=data.entity {
    node "state" id=ticket-state type=data.field { props required=#true }
}
node "State" id=state type=data.enum {
    - "open"
    - "closed"
}
edge state ticket-state
frame "Tickets API" id=api type=data.api {
    props api-version="3.2" auth="api-key"
    node "Get ticket" id=get-ticket type=data.operation { props method="get" path="/tickets/{ticket-id}" }
    node "Delete ticket" id=delete-ticket type=data.operation { props method="delete" path="/tickets/{ticket-id}" deprecated=#true }
}
edge get-ticket ticket label="200"
edge get-ticket ticket label="404"
"#;
    let b = build(src).unwrap();
    let state = parsed(&b, "specs/schemas/state.schema.json");
    assert_eq!(state["enum"], serde_json::json!(["open", "closed"]));
    let ticket = parsed(&b, "specs/schemas/ticket.schema.json");
    assert_eq!(
        ticket["properties"]["state"],
        serde_json::json!({ "$ref": "state.schema.json", "x-rhizo-node": "ticket-state" })
    );
    let api = parsed(&b, "specs/api.openapi.yaml");
    assert_eq!(api["openapi"], "3.2.0");
    let get = &api["paths"]["/tickets/{ticket-id}"]["get"];
    assert_eq!(get["parameters"][0]["name"], "ticket-id");
    assert_eq!(get["responses"]["404"]["description"], "Not Found");
    let delete = &api["paths"]["/tickets/{ticket-id}"]["delete"];
    assert_eq!(delete["responses"]["204"], serde_json::json!({ "description": "No Content" }));
    // A modeled 404 replaces the generic 4XX.
    assert!(get["responses"].get("4XX").is_none());
    assert!(delete["responses"].get("4XX").is_some());
    assert_eq!(delete["deprecated"], true);
    // The enum is reached through the ticket's field.
    let names: Vec<_> = api["components"]["schemas"].as_object().unwrap().keys().cloned().collect();
    assert_eq!(names, ["Ticket", "State", "Problem"]);
    assert_eq!(api["components"]["securitySchemes"]["apiKey"]["in"], "header");
}

