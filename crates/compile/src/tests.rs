#[test]
fn in_a_project_edges_stay_with_their_file() {
    // api file: the operation; flow file: a step that calls it.
    let src = r#"rhizo version=2
use data version="0.1"
frame "API" id=api type=data.api {
    node "Place order" id=place-order type=data.operation { props method="post" path="/orders" }
}
node "Confirm" id=confirm
edge place-order confirm
"#;
    let loaded = rhizo_lang::load(src, rhizo_lang::Syntax::Kdl);
    let doc = loaded.document;
    let origins = Origins {
        files: vec!["api.rhizo".into(), "flow.rhizo".into()],
        edge_file: vec![1],
        node_file: [("place-order".into(), 0), ("confirm".into(), 1)]
            .into_iter()
            .map(|(k, v): (String, usize)| (rhizo_core::NodeId(k), v))
            .collect(),
    };
    let b = compile_with(&doc, &Kits::builtin(), "p", src, Some(&origins)).unwrap();
    let t = tasks(&b);
    let op = t.iter().find(|x| x["id"] == "T-place-order").unwrap();
    assert_eq!(op["connections"], serde_json::json!([]), "the flow's edge is not the operation's");
    let md = &b.files[AGENTS].contents;
    assert!(!md.contains("- **Place order** (`data.operation`) → Confirm"), "{md}");
}

/// A large diagram plans in linear-ish time: 5,000 nodes in areas, a chain
/// of edges with forward skips and back edges (cycles to break). The old
/// quadratic brief took tens of seconds here in a debug build.
#[test]
fn brief_scales_to_large_diagrams() {
    let mut src = String::from("rhizo version=2\ntitle \"Big\"\nnode \"Ship\" id=goal type=rhizo.goal\n");
    let mut ids = Vec::new();
    for a in 0..500 {
        src += &format!("node \"Area {a}\" id=a{a} {{\n");
        for c in 0..9 {
            src += &format!("    node \"Part {a}-{c}\" id=p{a}x{c}\n");
            ids.push(format!("p{a}x{c}"));
        }
        src += "}\n";
    }
    for i in 1..ids.len() {
        src += &format!("edge {} {}\n", ids[i - 1], ids[i]);
        if i % 50 == 0 {
            src += &format!("edge {} {}\n", ids[i], ids[i - 40]);
        }
    }
    let loaded = rhizo_lang::load(&src, rhizo_lang::Syntax::Kdl);
    let start = std::time::Instant::now();
    let b = compile(&loaded.document, &Kits::builtin(), "big.rhizo", &src).unwrap();
    let took = start.elapsed();
    let tasks = parsed(&b, TASKS);
    assert_eq!(tasks["tasks"].as_array().unwrap().len(), 4500);
    assert!(took.as_secs() < 10, "compiling 5,000 nodes took {took:?}");
}
