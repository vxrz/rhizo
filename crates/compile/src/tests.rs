#[test]
fn brief_areas_scope_and_dependencies() {
    let src = r#"rhizo version=2
title "Launch"
node "Ship v1" id=goal type=rhizo.goal { accept "Public download page is live" }
node "Use Rust" id=rust type=rhizo.decision { props status="accepted" }
- "Launch" {
    - "Build" {
        - "CLI" { accept "Installs with cargo" }
        - "Docs"
    }
    - "Release" { note "Tag and publish." }
    - "Announce"
}
edge release announce
edge build release kind=dependency
edge announce build
edge rust build
edge goal announce
"#;
    let b = build(src).unwrap();
    let t = tasks(&b);
    let ids: Vec<&str> = t.iter().map(|x| x["id"].as_str().unwrap()).collect();
    assert_eq!(ids, ["T-build", "T-release", "T-announce"], "areas are not tasks; dependencies order them");
    assert_eq!(t[0]["area"], "Launch");
    assert_eq!(t[0]["scope"][0]["label"], "CLI");
    assert_eq!(t[0]["acceptance"][0]["text"], "CLI: Installs with cargo");
    assert_eq!(t[1]["depends-on"], json_list(&["T-build"]));
    assert_eq!(t[2]["depends-on"], json_list(&["T-release"]));
    // announce → build would close a cycle, so it is dropped.
    assert_eq!(t[0]["depends-on"], json_list(&[]));
    // Linked decisions and goals apply only to what they link to.
    assert_eq!(t[0]["decisions"], json_list(&["rust"]));
    assert_eq!(t[1]["decisions"], json_list(&[]));
    assert_eq!(t[2]["goals"], json_list(&["goal"]));
    let md = &b.files[AGENTS].contents;
    assert!(md.contains("Scope:\n\n- [ ] CLI\n  - must: Installs with cargo\n- [ ] Docs"), "{md}");
    assert!(md.contains("After: `T-release`."));
    // Deterministic.
    assert_eq!(build(src).unwrap().files, b.files);
}

#[test]
fn brief_builds_a_flow_as_one_task() {
    let src = r#"rhizo version=2
title "Invoices"
node "Archive everything" id=goal type=rhizo.goal
frame "Invoice inbox" id=inbox type=rhizo.flow layout=layered direction=right {
    props trigger="A new email in invoices@"
    node "Email arrives" id=email shape=pill
    node "Has PDF?" id=has-pdf
    node "Extract fields" id=extract { accept "Reads the IBAN" }
    node "Archive" id=archive
    edge email has-pdf
    edge has-pdf extract label="yes"
    edge has-pdf archive
    edge extract archive
}
node "Weekly report" id=report
edge archive report
"#;
    let b = build(src).unwrap();
    let t = tasks(&b);
    let ids: Vec<&str> = t.iter().map(|x| x["id"].as_str().unwrap()).collect();
    // A flow uses what it touches, so the report comes first.
    assert_eq!(ids, ["T-report", "T-inbox"]);
    let t = [t[1].clone(), t[0].clone()];
    assert_eq!(t[0]["kind"], "implement-flow");
    assert_eq!(t[0]["title"], "Implement the flow \"Invoice inbox\"");
    assert_eq!(t[0]["props"]["trigger"], "A new email in invoices@");
    let steps: Vec<&str> = t[0]["scope"].as_array().unwrap().iter().map(|s| s["label"].as_str().unwrap()).collect();
    assert_eq!(steps, ["Email arrives", "Has PDF?", "Extract fields", "Archive"]);
    assert_eq!(t[0]["scope"][1]["next"], json_list(&["Extract fields (yes)", "Archive"]));
    assert_eq!(t[0]["depends-on"], json_list(&["T-report"]));
    let q = parsed(&b, TASKS)["open-questions"].clone();
    let q: Vec<&str> = q.as_array().unwrap().iter().filter_map(|x| x.as_str()).collect();
    assert!(
        q.iter().any(|x| x.starts_with("At \"Has PDF?\", what decides between \"Extract fields\" or \"Archive\"?")),
        "{q:?}"
    );
    assert!(q.iter().any(|x| x.starts_with("Which technology stack")));
    assert!(q.iter().any(|x| x.starts_with("How will we know `T-report` is done?")), "{q:?}");
    let md = &b.files[AGENTS].contents;
    assert!(md.contains("## How it fits together"));
    assert!(md.contains("- **Has PDF?** → Extract fields (yes), → Archive"), "{md}");
}

#[test]
fn brief_narrates_a_sequence() {
    let src = r#"rhizo version=1
title "Login"
frame "Login" id=login layout=sequence {
    node "User" id=user
    node "App" id=app
    node "Auth" id=auth
    edge user app label="credentials"
    edge app auth
    edge auth app label="token" line=dashed
    edge app app label="store session"
}
"#;
    let b = build(src).unwrap();
    let t = tasks(&b);
    assert_eq!(t.len(), 1);
    assert_eq!(t[0]["kind"], "implement-sequence");
    assert_eq!(t[0]["title"], "Implement the sequence \"Login\"");
    let steps: Vec<&str> = t[0]["scope"].as_array().unwrap().iter().map(|s| s["label"].as_str().unwrap()).collect();
    assert_eq!(
        steps,
        [
            "1. User → App: credentials",
            "2. App → Auth: (no label)",
            "3. Auth → App: token (reply)",
            "4. App → itself: store session"
        ]
    );
    let q = parsed(&b, TASKS)["open-questions"].clone();
    assert!(
        q.as_array()
            .unwrap()
            .iter()
            .any(|x| x == "In \"Login\", what do these messages carry: 2 (App → Auth)? Label them."),
        "{q}"
    );
    let md = &b.files[AGENTS].contents;
    assert!(md.contains("A sequence between User, App, Auth.\n\n1. User → App: credentials\n"), "{md}");
}

