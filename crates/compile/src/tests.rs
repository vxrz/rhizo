fn tasks(b: &Bundle) -> Vec<serde_json::Value> {
    parsed(b, TASKS)["tasks"].as_array().unwrap().clone()
}

fn json_list(items: &[&str]) -> serde_json::Value {
    serde_json::json!(items)
}

