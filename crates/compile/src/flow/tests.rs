const SW_SCHEMA: &str = include_str!("../../tests/serverless-workflow/workflow-1.0.1.schema.yaml");

fn build(src: &str) -> Bundle {
    let loaded = rhizo_lang::load(src, rhizo_lang::Syntax::Kdl);
    assert!(!loaded.has_errors(), "{:?}", loaded.diagnostics);
    compile(&loaded.document, &Kits::builtin(), "orders.rhizo", src)
        .unwrap_or_else(|fs| panic!("{:#?}", fs.iter().map(|f| &f.diagnostic.message).collect::<Vec<_>>()))
}

fn file(b: &Bundle, path: &str) -> Value {
    let text = &b.files.get(path).unwrap_or_else(|| panic!("no {path} in {:?}", b.files.keys())).contents;
    if path.ends_with(".yaml") { serde_yaml_ng::from_str(text).unwrap() } else { serde_json::from_str(text).unwrap() }
}

fn sw_validator() -> jsonschema::Validator {
    let schema: Value = serde_yaml_ng::from_str(SW_SCHEMA).unwrap();
    jsonschema::draft202012::new(&schema).expect("the official schema compiles")
}

/// Every `.sw.yaml` in the bundle validates against the official schema.
fn assert_sw_valid(b: &Bundle) -> usize {
    let v = sw_validator();
    let mut n = 0;
    for path in b.files.keys().filter(|p| p.ends_with(".sw.yaml")) {
        let doc = file(b, path);
        let errors: Vec<String> = v.iter_errors(&doc).map(|e| format!("{}: {e}", e.instance_path())).collect();
        assert!(errors.is_empty(), "{path}:\n{}", errors.join("\n"));
        n += 1;
    }
    n
}

fn task<'a>(sw: &'a Value, name: &str) -> &'a Value {
    sw["do"].as_array().unwrap().iter().find_map(|t| t.get(name)).unwrap_or_else(|| panic!("no task {name}"))
}

#[test]
fn serverless_workflow_output_matches_the_official_schema() {
    let b = build(SRC);
    let flows: Vec<&str> = b.files.keys().filter(|p| p.starts_with("flows/")).map(String::as_str).collect();
    assert_eq!(
        flows,
        [
            "flows/node-red/intake.json",
            "flows/serverless-workflow/intake.sw.yaml",
            "flows/serverless-workflow/nightly.sw.yaml",
            "flows/serverless-workflow/on-event.sw.yaml",
        ]
    );
    assert_eq!(assert_sw_valid(&b), 3);
    // The validator is not vacuous.
    let mut broken = file(&b, "flows/serverless-workflow/intake.sw.yaml");
    broken["document"]["name"] = json!("Not a name!");
    assert!(!sw_validator().is_valid(&broken));
    let mut broken = file(&b, "flows/serverless-workflow/intake.sw.yaml");
    broken["do"][0]["score"]["run"]["script"]["language"] = json!(7);
    assert!(!sw_validator().is_valid(&broken));

    let sw = file(&b, "flows/serverless-workflow/intake.sw.yaml");
    assert!(b.files["flows/serverless-workflow/intake.sw.yaml"].contents.starts_with("# @generated by rhizo"));
    assert_eq!(
        sw["document"],
        json!({
            "dsl": "1.0.1", "namespace": "shop", "name": "intake", "version": "1.2.0", "title": "Order intake",
            "summary": "Takes partner orders",
            "metadata": { "rhizo-source": "orders.rhizo", "rhizo-frame": "intake", "rhizo-trigger": "received", "rhizo-webhook": "POST /orders" }
        })
    );
    let names: Vec<&str> =
        sw["do"].as_array().unwrap().iter().map(|t| t.as_object().unwrap().keys().next().unwrap().as_str()).collect();
    assert_eq!(names, ["score", "risky", "review", "place", "wait", "done"], "flow order");
    assert_eq!(
        task(&sw, "risky")["switch"],
        json!([{ "review": { "when": "${ .risk > 0.8 }", "then": "review" } }, { "default": { "then": "place" } }])
    );
    let review = task(&sw, "review");
    assert_eq!(review["then"], "end", "the branch ends instead of running into `place`");
    assert_eq!(
        review["with"],
        json!({
            "method": "post", "endpoint": "https://review.example.com/cases", "headers": { "X-Key": "abc" },
            "body": { "order": "${ .id }", "why": r#"${ "risk " + (.risk | tostring) }"# }
        })
    );
    let place = task(&sw, "place");
    assert_eq!(
        place["with"],
        json!({ "method": "post", "endpoint": "https://api.example.com/orders", "body": "${ . }" }),
        "method, path and server from the operation"
    );
    assert!(place.get("then").is_none());
    assert_eq!(task(&sw, "wait")["wait"], json!({ "seconds": 2 }));
    assert_eq!(task(&sw, "done")["set"], json!({ "status": "ok", "order": r#"${ ."order-id" }"#, "n": 3 }));
    assert_eq!(task(&sw, "done")["metadata"], json!({ "rhizo-node": "done" }));
    let score = task(&sw, "score");
    let code = score["run"]["script"]["code"].as_str().unwrap();
    assert!(code.contains("// TODO(rhizo T-score): implement \"Score\""), "{code}");
    assert!(code.contains("// New customers score higher\n"), "{code}");
    assert_eq!(score["output"]["as"], "${ fromjson }");

    let nightly = file(&b, "flows/serverless-workflow/nightly.sw.yaml");
    assert_eq!(nightly["schedule"], json!({ "cron": "0 2 * * *" }));
    assert_eq!(
        task(&nightly, "small")["switch"][1],
        json!({ "default": { "then": "end" } }),
        "no default: the workflow ends"
    );
    assert_eq!(
        task(&nightly, "run-intake")["run"],
        json!({ "workflow": { "namespace": "shop", "name": "intake", "version": "1.2.0" } })
    );
    let on_event = file(&b, "flows/serverless-workflow/on-event.sw.yaml");
    assert_eq!(on_event["schedule"]["on"]["one"]["with"]["type"], "com.example.order.placed");
    let code = task(&on_event, "noted")["run"]["script"]["code"].as_str().unwrap();
    assert_eq!(
        code,
        "const run = (data) => {\n  return { seen: true };\n};\nconsole.log(JSON.stringify(run(data)));\n"
    );
}

/// Structure Node-RED needs to import a flow: one tab, unique editor-style
/// ids, every node on the tab, wires to nodes that exist, and the fields
/// each core node type reads.
fn assert_node_red_valid(flow: &Value) {
    let nodes = flow.as_array().expect("a flows.json is an array");
    let tab = &nodes[0];
    assert_eq!(tab["type"], "tab");
    let mut ids = HashSet::new();
    for n in nodes {
        let id = n["id"].as_str().expect("every node has an id");
        assert!(id.len() == 16 && id.bytes().all(|b| b.is_ascii_hexdigit()), "{id}");
        assert!(ids.insert(id), "duplicate id {id}");
    }
    for n in &nodes[1..] {
        assert_eq!(n["z"], tab["id"], "{n}");
        assert!(n["x"].is_u64() && n["y"].is_u64() && n["name"].is_string(), "{n}");
        assert!(n["info"].as_str().is_some_and(|i| !i.is_empty()), "{n}");
        let wires = n["wires"].as_array().expect("wires");
        for to in wires.iter().flat_map(|w| w.as_array().unwrap()) {
            assert!(ids.contains(to.as_str().unwrap()), "{} wires to unknown {to}", n["id"]);
        }
        let has = |keys: &[&str]| keys.iter().all(|k| n.get(*k).is_some());
        let ok = match n["type"].as_str().unwrap() {
            "http in" => has(&["url", "method"]) && wires.len() == 1,
            "http response" => has(&["statusCode", "headers"]) && wires.is_empty(),
            "http request" => has(&["method", "url", "ret", "paytoqs", "headers"]) && wires.len() == 1,
            "inject" => has(&["props", "crontab", "repeat", "payloadType"]) && wires.len() == 1,
            "switch" => {
                let rules = n["rules"].as_array().unwrap();
                n["outputs"] == rules.len() && wires.len() == rules.len() && has(&["property", "checkall"])
            }
            "change" => n["rules"].as_array().is_some_and(|r| !r.is_empty()) && wires.len() == 1,
            "delay" => has(&["pauseType", "timeout", "timeoutUnits"]) && wires.len() == 1,
            "catch" => has(&["scope", "uncaught"]) && wires.len() == 1,
            "function" => has(&["func", "outputs", "libs"]) && wires.len() == 1,
            other => panic!("unexpected node type {other}"),
        };
        assert!(ok, "{n}");
    }
}

#[test]
fn node_red_output_is_importable() {
    let b = build(SRC);
    let flow = file(&b, "flows/node-red/intake.json");
    assert_node_red_valid(&flow);
    let nodes = flow.as_array().unwrap();
    let by_name = |name: &str| nodes.iter().find(|n| n["name"] == name).unwrap_or_else(|| panic!("no {name}"));
    let id = |name: &str| by_name(name)["id"].clone();
    let types: Vec<&str> = nodes.iter().map(|n| n["type"].as_str().unwrap()).collect();
    assert_eq!(
        types,
        [
            "tab",
            "http in",
            "function",
            "switch",
            "change",
            "http request",
            "http request",
            "delay",
            "change",
            "http response",
            "catch",
            "http response"
        ]
    );
    // A failed step answers 500; a failed request does not go on as data.
    assert_eq!(by_name("Step failed")["wires"], json!([[id("Reply: failed")]]));
    assert_eq!(by_name("Reply: failed")["statusCode"], "500");
    assert_eq!(by_name("Place")["senderr"], true);
    assert!(nodes[0]["info"].as_str().unwrap().starts_with("@generated by rhizo"));
    assert_eq!(by_name("Received")["url"], "/orders");
    assert_eq!(by_name("Received")["wires"], json!([[id("Score")]]));
    let risky = by_name("Risky?");
    assert_eq!(
        risky["rules"],
        json!([{ "t": "jsonata_exp", "v": "payload.risk > 0.8", "vt": "jsonata" }, { "t": "else" }])
    );
    assert_eq!(risky["wires"], json!([[id("Review: body")], [id("Place")]]));
    assert_eq!(by_name("Review: body")["rules"][0]["to"], r#"{"order": payload.id, "why": "risk " & payload.risk}"#);
    assert_eq!(by_name("Review: body")["wires"], json!([[id("Review")]]));
    assert_eq!(
        by_name("Review")["headers"][0],
        json!({ "keyType": "other", "keyValue": "X-Key", "valueType": "other", "valueValue": "abc" })
    );
    // Both ends of the webhook flow answer the request.
    assert_eq!(by_name("Review")["wires"], json!([[id("Reply")]]));
    assert_eq!(by_name("Done")["wires"], json!([[id("Reply")]]));
    assert_eq!(by_name("Place")["url"], "https://api.example.com/orders");
    assert_eq!(by_name("Place")["method"], "POST");
    assert_eq!(by_name("Wait")["timeout"], "2");
    assert_eq!(by_name("Done")["rules"][0]["to"], r#"{"status": "ok", "order": payload.`order-id`, "n": 3}"#);
    let func = by_name("Score")["func"].as_str().unwrap();
    assert!(
        func.contains("TODO(rhizo T-score)") && func.ends_with("msg.payload = run(msg.payload);\nreturn msg;\n"),
        "{func}"
    );
    assert!(by_name("Score")["info"].as_str().unwrap().contains("rhizo node `score` (flow.script)"));

    // A schedule trigger, and a switch without a default outside a webhook flow.
    let src = r#"rhizo version=2
use flow version="0.1"
frame "Morning" id=morning type=flow.workflow {
    node "At 7" id=at-7 type=flow.trigger.schedule { props cron="0 7 * * 1-5" }
    node "Weekend?" id=weekend type=flow.switch
    node "Stamp" id=stamp type=flow.transform { props { set { kind "morning" } } }
    edge at-7 weekend
    edge weekend stamp label="day > 5"
}
"#;
    let flow = file(&build(src), "flows/node-red/morning.json");
    assert_node_red_valid(&flow);
    let nodes = flow.as_array().unwrap();
    assert_eq!(nodes[1]["crontab"], "0 7 * * 1-5");
    assert_eq!(nodes[2]["rules"].as_array().unwrap().len(), 1, "no else: the message stops");
    assert_eq!(nodes[3]["wires"], json!([[]]));
}

#[test]
fn flow_output_is_deterministic_and_ids_are_stable() {
    let a = build(SRC);
    assert_eq!(a.files, build(SRC).files);
    let ids = |b: &Bundle| -> Vec<(String, String)> {
        file(b, "flows/node-red/intake.json")
            .as_array()
            .unwrap()
            .iter()
            .map(|n| (n["name"].as_str().unwrap_or("").to_string(), n["id"].as_str().unwrap().to_string()))
            .collect()
    };
    // Adding a step keeps every other node's id, so a re-import updates in place.
    let more = SRC.replace(
        "edge place wait done\n",
        "node \"Pause\" id=pause type=flow.delay { props seconds=1 }\n    edge place wait done pause\n",
    );
    let before = ids(&a);
    let after = ids(&build(&more));
    assert_eq!(after.len(), before.len() + 1);
    for pair in &before {
        assert!(after.contains(pair), "{pair:?} changed");
    }
}

#[test]
fn brief_leaves_only_scripts_and_deploys() {
    let b = build(SRC);
    let tasks = file(&b, TASKS)["tasks"].as_array().unwrap().clone();
    let summary: Vec<(String, String, Value)> = tasks
        .iter()
        .map(|t| (t["id"].as_str().unwrap().into(), t["kind"].as_str().unwrap().into(), t["depends-on"].clone()))
        .collect();
    assert_eq!(
        summary,
        [
            ("T-place-order".into(), "implement".into(), json!([])),
            ("T-score".into(), "implement".into(), json!([])),
            ("T-intake-deploy".into(), "human".into(), json!(["T-place-order", "T-score"])),
            ("T-nightly-deploy".into(), "human".into(), json!([])),
            ("T-on-event-deploy".into(), "human".into(), json!([])),
        ],
        "compiled steps and scripts with code need no task"
    );
    let score = &tasks[1];
    assert_eq!(score["title"], "Implement the script step \"Score\"");
    assert_eq!(
        score["inputs"],
        // Only direct neighbours count: the API spec is two steps away.
        json!(["flows/node-red/intake.json", "flows/serverless-workflow/intake.sw.yaml"])
    );
    assert_eq!(score["acceptance"][0], json!({ "source": "authored", "text": "New customers score higher" }));
    assert_eq!(score["acceptance"][1]["source"], "flow");
    let deploy = &tasks[2];
    assert_eq!(deploy["title"], "Deploy the workflow \"Order intake\"");
    assert_eq!(deploy["frame"], "intake");
    let criteria: Vec<&str> =
        deploy["acceptance"].as_array().unwrap().iter().map(|a| a["text"].as_str().unwrap()).collect();
    assert_eq!(
        criteria,
        [
            "Node-RED imports `flows/node-red/intake.json` and deploys it without errors",
            "A Serverless Workflow engine (DSL 1.0.1) accepts `flows/serverless-workflow/intake.sw.yaml`",
            "POST /orders starts the workflow on the Serverless Workflow engine too (engines start workflows through their own API: expose it there)",
            "Every endpoint the HTTP steps call is reachable from the runtime, with its credentials set there (the generated files hold no secrets)",
        ],
        "the script's own criteria stay with its task"
    );
    let questions = file(&b, TASKS)["open-questions"].to_string();
    assert!(!questions.contains("deploy"), "{questions}");
    let md = &b.files[crate::AGENTS].contents;
    assert!(md.contains("- `flows/node-red/intake.json`"), "listed with the generated files");
    assert!(md.contains("### 3. Deploy the workflow \"Order intake\" (`T-intake-deploy`)"), "{md}");
}

#[test]
fn the_shop_example_compiles_as_a_project() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../examples/shop");
    let p = rhizo_project::Project::load_dir(&dir).unwrap();
    let problems: Vec<String> = p.check(&Kits::builtin()).into_iter().flatten().map(|d| d.message).collect();
    assert!(problems.is_empty(), "{problems:?}");
    let b = compile(&p.merged, &Kits::builtin(), &p.name(), &p.sources()).unwrap();
    assert_eq!(assert_sw_valid(&b), 1);
    let sw = file(&b, "flows/serverless-workflow/order-intake.sw.yaml");
    assert_eq!(task(&sw, "place")["with"]["endpoint"], "https://api.shop.example/orders", "from api.rhizo");
    assert_node_red_valid(&file(&b, "flows/node-red/order-intake.json"));
    let tasks = file(&b, TASKS)["tasks"].to_string();
    assert!(tasks.contains("\"T-order-intake-deploy\"") && tasks.contains("\"T-score\""));
}
