    /// The root module's variables: each name with its block.
    pub(super) fn variable_blocks(&self) -> Vec<(String, Item)> {
        let var = |name: &str, ty: &str, desc: String, extra: Vec<Item>| {
            let mut items = vec![a("description", q(&desc)), a("type", ty)];
            if !extra.is_empty() {
                items.push(Item::Blank);
                items.extend(extra);
            }
            (name.to_string(), block(format!("variable \"{name}\""), items))
        };
        let check = |v: &str, re: &str, msg: &str| {
            vec![block(
                "validation",
                vec![a("condition", format!("can(regex({}, var.{v}))", q(re))), a("error_message", q(msg))],
            )]
        };
        let mut out = vec![var(
            "project_id",
            "string",
            format!("The existing Google Cloud project the {} environment is deployed to.", self.frame.id),
            check("project_id", "^[a-z][a-z0-9-]{4,28}[a-z0-9]$", "project_id is a Google Cloud project id."),
        )];
        if k::gcp_state(self.frame).is_some() {
            out.push(var(
                "state_kms_key",
                "string",
                "The existing Cloud KMS key that encrypts state and plans (encryption.tofu), projects/…/cryptoKeys/…."
                    .into(),
                check(
                    "state_kms_key",
                    "^projects/[^/]+/locations/[^/]+/keyRings/[^/]+/cryptoKeys/[^/]+$",
                    "state_kms_key is a Cloud KMS key name.",
                ),
            ));
        }
        if self.frame.props.contains_key("budget-monthly") {
            out.push(var(
                "billing_account_id",
                "string",
                "The billing account the project is billed to; the budget belongs to it.".into(),
                check(
                    "billing_account_id",
                    "^[0-9A-F]{6}-[0-9A-F]{6}-[0-9A-F]{6}$",
                    "billing_account_id looks like 012345-6789AB-CDEF01.",
                ),
            ));
            out.push(var("budget_alert_emails", "list(string)", "Who gets budget alerts.".into(), vec![]));
        }
        for n in self.of(FUNCTION) {
            out.push(var(
                &format!("{}_package", addr(n.id.as_str())),
                "string",
                format!("Path to the source zip of {} (built by task T-{}).", n.label, n.id),
                vec![],
            ));
        }
        for n in self.of(POSTGRES) {
            out.push(var(
                &format!("{}_admin_group", addr(n.id.as_str())),
                "string",
                format!("Email of the Google group that administers {} ({}) as cloudsqlsuperuser.", n.label, n.id),
                vec![],
            ));
        }
        out
    }

    fn outputs(&self) -> String {
        let mut groups = Vec::new();
        for n in &self.nodes {
            let ma = m(n);
            let a_ = addr(n.id.as_str());
            let mut push = |suffix: &str, value: String, what: &str| {
                groups.push(vec![block(
                    format!("output \"{a_}_{suffix}\""),
                    vec![a("description", q(&format!("{what} of {} ({})", n.label, n.id))), a("value", value)],
                )]);
            };
            match k::ty(n) {
                VPC => push("network", format!("{ma}.network_self_link"), "VPC network"),
                BUCKET => push("bucket", format!("{ma}.name"), "Bucket name"),
                TABLE => push("database", format!("google_firestore_database.{a_}.name"), "Firestore database"),
                POSTGRES => {
                    push("connection_name", format!("{ma}.instance_connection_name"), "Cloud SQL connection name");
                    push("private_ip", format!("{ma}.private_ip_address"), "Database private IP");
                }
                QUEUE => push("topic", format!("{ma}.id"), "Pub/Sub topic"),
                TOPIC => push("topic", format!("{ma}.id"), "Pub/Sub topic"),
                KEY => push("key", Self::key_id(n), "Cloud KMS key"),
                FUNCTION => push("uri", Self::uri(n), "Function URL"),
                HTTP_API => push(
                    "url",
                    format!("\"https://${{google_api_gateway_gateway.{a_}.default_hostname}}\""),
                    "Base URL",
                ),
                _ => {}
            }
        }
        file(&self.header, groups)
    }
