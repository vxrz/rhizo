//! The Google Cloud compiler for the cloud-neutral `infra.*` types: an
//! environment with `cloud="gcp"` becomes one OpenTofu root module of
//! terraform-google-modules (docs/design/infra-cloud-neutral.md, step 4).
//!
//! - `versions.tf`: OpenTofu and the providers pinned exactly, the gcs
//!   backend; `encryption.tofu` encrypts state and plans with Cloud KMS.
//! - `providers.tf`, `main.tf` (the project's APIs, modules pinned to exact
//!   versions, raw resources where no module fits), `iam.tf` (a service
//!   account per function and least-privilege bindings on each resource),
//!   `variables.tf` (the project and people, without defaults) and
//!   `outputs.tf`.
//!
//! rhizo deploys into an existing project and creates no projects. What has
//! no faithful Google Cloud mapping is a finding of the kit rules
//! (`rhizo_kit::infra::gcp::gaps`), never dropped here.

