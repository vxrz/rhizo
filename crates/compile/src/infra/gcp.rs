    /// The routes of an API, as OpenAPI 2.0 operations by path.
    fn operations(&self, api: &Node) -> Vec<(String, Vec<Item>)> {
        let mut paths: Vec<(String, Vec<Item>)> = Vec::new();
        for (e, f) in self.links_from(api, Link::Route) {
            for r in k::routes(self.doc, e) {
                let Some((method, path)) = r.split_once(' ') else { continue };
                let methods: Vec<String> = if method == "ANY" {
                    ["delete", "get", "head", "patch", "post", "put"].map(String::from).to_vec()
                } else {
                    vec![method.to_lowercase()]
                };
                let params: Vec<String> = path
                    .split('/')
                    .filter_map(|s| s.strip_prefix('{').and_then(|s| s.strip_suffix('}')))
                    .map(|p| format!("{{ in = \"path\", name = {}, required = true, type = \"string\" }}", q(p)))
                    .collect();
                let slug = name(path).replace('-', "_");
                for method in methods {
                    let mut op = vec![
                        a("operationId", q(&format!("{method}_{}", if slug.is_empty() { "root" } else { &slug }))),
                        a("summary", q(&format!("rhizo:edge={}->{} {r}", api.id, f.id))),
                    ];
                    if !params.is_empty() {
                        op.push(a("parameters", list(params.clone())));
                    }
                    op.extend([
                        a(
                            "\"x-google-backend\"",
                            format!(
                                "{{ address = {}, path_translation = \"APPEND_PATH_TO_ADDRESS\", deadline = {} }}",
                                Self::uri(f),
                                g::int(f, "timeout-s", 10).min(g::MAX_WAIT_S)
                            ),
                        ),
                        a("responses", "{ default = { description = \"The function's response\" } }"),
                    ]);
                    let entry = obj(&method, op);
                    match paths.iter_mut().find(|(p, _)| p == path) {
                        Some((_, ops)) => ops.push(entry),
                        None => paths.push((path.to_string(), vec![entry])),
                    }
                }
            }
        }
        paths
    }

