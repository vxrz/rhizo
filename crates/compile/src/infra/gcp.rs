/// The catalog: exact versions, checked against registry.opentofu.org and
/// each module's `versions.tf` on 2026-10-22 (latest release of each).
/// `tofu init` resolves every module's provider ranges to these.
const GOOGLE: &str = "7.46.1"; // the newest 7.x: the pubsub module needs < 8, the sql module >= 7.22
const NULL: &str = super::NULL; // the sql module needs null and random
const RANDOM: &str = super::RANDOM;

