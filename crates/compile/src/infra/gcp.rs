    /// Environment variables a function finds its resources by, from its edges.
    pub(super) fn wiring(&self, n: &Node) -> Vec<(String, String)> {
        let mut vars = vec![("GOOGLE_CLOUD_PROJECT".to_string(), "local.project".to_string())];
        for (e, s) in self.links_from(n, Link::Grant) {
            let (ms, up) = (m(s), upper(s.id.as_str()));
            let (read, write) = k::access(e, s).unwrap_or((true, true));
            match k::ty(s) {
                BUCKET => vars.push((format!("{up}_BUCKET"), format!("{ms}.name"))),
                TABLE => vars.extend([
                    (format!("{up}_DATABASE"), format!("google_firestore_database.{}.name", addr(s.id.as_str()))),
                    (format!("{up}_COLLECTION"), q(&name(s.id.as_str()))),
                ]),
                QUEUE => {
                    if write {
                        vars.push((format!("{up}_TOPIC"), format!("{ms}.id")));
                    }
                    if read {
                        for (i, sub) in self.queue_subs(s).iter().enumerate() {
                            let key = if i == 0 {
                                format!("{up}_SUBSCRIPTION")
                            } else {
                                format!("{up}_SUBSCRIPTION_{}", i + 1)
                            };
                            vars.push((key, format!("\"projects/${{local.project}}/subscriptions/{sub}\"")));
                        }
                    }
                }
                TOPIC => vars.push((format!("{up}_TOPIC"), format!("{ms}.id"))),
                POSTGRES => vars.extend([
                    (format!("{up}_INSTANCE"), format!("{ms}.instance_connection_name")),
                    (format!("{up}_HOST"), format!("{ms}.private_ip_address")),
                    (format!("{up}_PORT"), q("5432")),
                    (
                        format!("{up}_NAME"),
                        q(&g::text(s, "database").map_or_else(|| addr(s.id.as_str()), str::to_string)),
                    ),
                    (format!("{up}_USER"), format!("trimsuffix({}.email, \".gserviceaccount.com\")", self.fn_sa(n))),
                ]),
                _ => {}
            }
        }
        let origins: Vec<&str> = self
            .links_to(n, Link::Route)
            .iter()
            .flat_map(|(_, api)| api.props.get("cors-origins").and_then(Value::as_array).into_iter().flatten())
            .filter_map(Value::as_str)
            .collect();
        if !origins.is_empty() {
            let mut o: Vec<&str> = origins;
            o.dedup();
            vars.push(("CORS_ALLOWED_ORIGINS".into(), q(&o.join(","))));
        }
        let mut seen = BTreeSet::new();
        vars.retain(|(k_, _)| seen.insert(k_.clone()));
        vars
    }

