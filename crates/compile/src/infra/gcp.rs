    /// `depends_on` for a topic module whose key must be granted first.
    fn topic_wait(&self, n: &Node) -> Vec<Item> {
        self.key_grant(n).map_or_else(Vec::new, |grant| vec![Item::Blank, a("depends_on", format!("[{grant}]"))])
    }

    /// A queue: a topic, the subscription its consumers use, and a
    /// dead-letter topic with a subscription that keeps what failed.
    fn queue(&self, n: &Node) -> Vec<Vec<Item>> {
        let id = n.id.as_str();
        let base = self.base(n);
        let mut items = self.topic_base(n, base.clone());
        items.extend(Self::subscriptions(vec![self.queue_sub(n, base.clone())]));
        items.extend(self.topic_wait(n));
        let mut out = vec![vec![comment(format!("rhizo:node={id}")), module_block(&addr(id), PUBSUB, items)]];
        if g::flag(n, "dlq", true) {
            let dl = format!("{base}-dead-letter");
            let mut items = self.topic_base(n, dl.clone());
            items.extend(Self::subscriptions(vec![Sub {
                push: None,
                items: vec![
                    a("name", q(&dl)),
                    a("message_retention_duration", q("1209600s")),
                    a("expiration_policy", q("")),
                ],
            }]));
            items.extend(self.topic_wait(n));
            out.push(vec![
                comment(format!("rhizo:node={id}: messages that failed max-deliveries times")),
                module_block(&format!("{}_dead_letter", addr(id)), PUBSUB, items),
            ]);
        }
        out
    }

    /// The names of a queue's subscriptions: its own, then one per topic
    /// that feeds it.
    fn queue_subs(&self, qn: &Node) -> Vec<String> {
        let mut out = vec![self.base(qn)];
        out.extend(
            self.links_to(qn, Link::Subscribe)
                .iter()
                .map(|(_, t)| format!("{}-from-{}", self.base(qn), name(t.id.as_str()))),
        );
        out
    }

    fn topic(&self, t: &Node) -> Vec<Item> {
        let mut items = self.topic_base(t, self.base(t));
        let mut subs = Vec::new();
        for (_, s) in self.links_from(t, Link::Subscribe) {
            if k::ty(s) == QUEUE {
                let mut sub = self.queue_sub(s, format!("{}-from-{}", self.base(s), name(t.id.as_str())));
                sub.items.insert(
                    0,
                    comment(format!("rhizo:edge={}->{} (the queue's subscription on this topic)", t.id, s.id)),
                );
                subs.push(sub);
            } else {
                let wait = g::int(s, "timeout-s", 10).clamp(g::ACK_S.0, g::ACK_S.1);
                let sub = format!("{}-to-{}", self.base(t), name(s.id.as_str()));
                subs.push(Sub {
                    push: Some(s.id.to_string()),
                    items: vec![
                        comment(format!("rhizo:edge={}->{} (subscription)", t.id, s.id)),
                        a("name", q(&sub)),
                        a("push_endpoint", Self::uri(s)),
                        a("audience", Self::uri(s)),
                        a("oidc_service_account_email", format!("{}.email", self.sa(PUSH))),
                        a("ack_deadline_seconds", wait.to_string()),
                        a("enable_message_ordering", g::flag(t, "fifo", false).to_string()),
                        a("expiration_policy", q("")),
                    ],
                });
            }
        }
        items.extend(Self::subscriptions(subs));
        items.extend(self.topic_wait(t));
        items
    }

