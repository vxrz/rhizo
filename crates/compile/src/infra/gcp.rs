    /// A queue's subscription settings, for its own topic or a topic that
    /// feeds it.
    fn queue_sub(&self, qn: &Node, sub: String) -> Sub {
        let trigger = self.links_from(qn, Link::Trigger).into_iter().map(|(_, f)| f).next();
        let mut items = vec![a("name", q(&sub))];
        if let Some(f) = trigger {
            items.extend([
                comment(format!("rhizo:edge={}->{} (trigger)", qn.id, f.id)),
                a("push_endpoint", Self::uri(f)),
                a("audience", Self::uri(f)),
                a("oidc_service_account_email", format!("{}.email", self.sa(PUSH))),
            ]);
        }
        items.extend([
            a("ack_deadline_seconds", g::int(qn, "visibility-timeout-s", 30).to_string()),
            a("message_retention_duration", q(&format!("{}s", g::int(qn, "retention-s", 345_600)))),
            a("enable_message_ordering", g::flag(qn, "fifo", false).to_string()),
            a("expiration_policy", q("")),
        ]);
        if g::flag(qn, "dlq", true) {
            items.extend([
                a("dead_letter_topic", format!("{}_dead_letter.id", m(qn))),
                a("max_delivery_attempts", g::int(qn, "max-receives", 5).to_string()),
            ]);
        }
        Sub { push: trigger.map(|f| f.id.to_string()), items }
    }

    /// Subscriptions grouped by kind: (push, pull) as module inputs.
    fn subscriptions(subs: Vec<Sub>) -> Vec<Item> {
        let (push, pull): (Vec<Sub>, Vec<Sub>) = subs.into_iter().partition(|s| s.push.is_some());
        let mut out = Vec::new();
        for (key, group) in [("push_subscriptions", push), ("pull_subscriptions", pull)] {
            if !group.is_empty() {
                out.extend([
                    Item::Blank,
                    Item::Attr(key.into(), Val::Objs(group.into_iter().map(|s| s.items).collect())),
                ]);
            }
        }
        out
    }

