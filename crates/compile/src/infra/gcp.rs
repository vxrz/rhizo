/// What the generated Google Cloud infrastructure expects of a function's code.
pub(super) fn function_criteria(doc: &Document, frame: &Frame, f: &Node) -> Vec<Criterion> {
    let env = Gcp::new(doc, frame, "");
    let dir = dir(frame);
    let fa = addr(f.id.as_str());
    let runtime = g::runtime(g::text(f, "runtime").unwrap_or("nodejs22.x")).unwrap_or_else(|| "nodejs22".into());
    let handler = g::text(f, "handler").unwrap_or("handler");
    let entry = handler.rsplit('.').next().unwrap_or(handler);
    let mut out = vec![Criterion::new(
        "infra",
        format!(
            "Builds into a source zip for Cloud Run functions runtime `{runtime}` whose entry point `{entry}` is exported by the runtime's main file (`index.js` or package.json `main`, `main.py`, …); `var.{fa}_package` in `{dir}/variables.tf` points at it"
        ),
    )];
    let vars: Vec<String> = env.wiring(f).into_iter().map(|(k_, _)| format!("`{k_}`")).collect();
    out.push(Criterion::new(
        "infra",
        format!(
            "Signs in as its service account (Application Default Credentials), never with keys, and finds its resources through the environment variables in `{dir}/main.tf` ({})",
            vars.join(", ")
        ),
    ));
    let mut writes_objects = false;
    for (_, e, a_, b, l) in k::links(doc) {
        match l {
            Link::Grant if a_.id == f.id && k::ty(b) == POSTGRES => out.push(Criterion::new(
                "infra",
                format!(
                    "Connects to `{}` through the Cloud SQL connector (private IP, IAM database authentication) as its service account's database user (`{}_USER`); a migration run by the database's admin group grants that role what it needs",
                    b.id,
                    upper(b.id.as_str())
                ),
            )),
            Link::Grant if a_.id == f.id && k::ty(b) == BUCKET => {
                writes_objects |= k::access(e, b).is_ok_and(|(_, w)| w);
            }
            Link::Trigger if b.id == f.id => out.push(Criterion::new(
                "infra",
                format!(
                    "Takes the messages of queue `{}` as Pub/Sub push requests (HTTP POST with the message envelope{}) and answers 2xx only for a processed message, so a failed one is retried and then dead-lettered",
                    a_.id,
                    if g::flag(a_, "fifo", false) { ", in order per ordering key" } else { "" }
                ),
            )),
            Link::Subscribe if b.id == f.id => out.push(Criterion::new(
                "infra",
                format!(
                    "Handles the push messages of topic `{}` idempotently (Pub/Sub delivers at least once)",
                    a_.id
                ),
            )),
            Link::Route if b.id == f.id => {
                for r in k::routes(doc, e) {
                    out.push(Criterion::new(
                        "infra",
                        format!("Serves `{r}` over HTTP; API Gateway calls it with an ID token of its own service account"),
                    ));
                }
                if a_.props.get("cors-origins").and_then(Value::as_array).is_some_and(|o| !o.is_empty()) {
                    out.push(Criterion::new(
                        "infra",
                        "Answers CORS preflight (`OPTIONS`) requests and sets `Access-Control-Allow-Origin` for the origins in `CORS_ALLOWED_ORIGINS`: API Gateway passes them through",
                    ));
                }
            }
            _ => {}
        }
    }
    if writes_objects {
        out.push(Criterion::new(
            "infra",
            "Writes objects under new names: overwriting one needs delete, which access=write and read-write do not grant",
        ));
    }
    if k::links(doc).any(|(_, _, a_, _, l)| a_.id == f.id && l == Link::Grant) {
        out.push(Criterion::new(
            "infra",
            format!(
                "Needs no access beyond the IAM bindings in `{dir}/iam.tf`; a missing one is a change to the diagram"
            ),
        ));
    }
    out
}
