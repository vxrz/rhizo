    /// IAM bindings: each function's service account gets what its edges
    /// say, on the one resource; service agents get the keys of the stores
    /// they encrypt.
    fn iam(&self) -> (Vec<Vec<Item>>, Vec<String>) {
        let mut groups = Vec::new();
        let mut nodes = BTreeSet::new();
        let member = |key: &str| format!("{}.member", self.sa(key));
        let res = |kind: &str, name: String, edge: String, mut items: Vec<Item>| {
            items.insert(0, comment(edge));
            let body = items.split_off(1);
            let mut v = items;
            v.push(block(format!("resource \"{kind}\" \"{name}\""), body));
            v
        };
        for (key, service, stores) in self.encrypted() {
            let ka = addr(key.id.as_str());
            nodes.insert(key.id.to_string());
            nodes.extend(stores.iter().map(|s| s.id.to_string()));
            let agent = if service == "storage" {
                "data.google_storage_project_service_account.current.member".to_string()
            } else {
                format!(
                    "\"serviceAccount:${{module.project_services.enabled_api_identities[\"{service}.googleapis.com\"]}}\""
                )
            };
            groups.push(res(
                "google_kms_crypto_key_iam_member",
                format!("{ka}_{service}"),
                format!(
                    "rhizo:edge={}: the {service} service agent encrypts them with the key",
                    stores.iter().map(|s| format!("{}->{}", s.id, key.id)).collect::<Vec<_>>().join(" ")
                ),
                vec![a("crypto_key_id", Self::key_id(key)), a("role", q(KEY_USER)), a("member", agent)],
            ));
        }
        if self.any(FUNCTION) {
            let b = addr(BUILDER);
            let builder = member(BUILDER);
            groups.push(res(
                "google_storage_bucket_iam_member",
                format!("{b}_sources"),
                "The builder reads the function sources".into(),
                vec![
                    a("bucket", "module.function_sources.name"),
                    a("role", q(OBJECT_VIEWER)),
                    a("member", builder.clone()),
                ],
            ));
            groups.push(res(
                "google_artifact_registry_repository_iam_member",
                format!("{b}_images"),
                "The builder pushes the function images".into(),
                vec![
                    a("project", "local.project"),
                    a("location", "local.region"),
                    a("repository", "google_artifact_registry_repository.functions.name"),
                    a("role", q("roles/artifactregistry.writer")),
                    a("member", builder.clone()),
                ],
            ));
            groups.push(res(
                "google_project_iam_member",
                format!("{b}_logs"),
                "The builder writes build logs (a project role: logs have no resource-level binding)".into(),
                vec![a("project", "local.project"), a("role", q("roles/logging.logWriter")), a("member", builder)],
            ));
        }
        for f in self.of(FUNCTION) {
            let fa = addr(f.id.as_str());
            let principal = format!("{}.member", self.fn_sa(f));
            for (e, s) in self.links_from(f, Link::Grant) {
                let Ok((read, write)) = k::access(e, s) else { continue };
                let access = match (read, write) {
                    (true, true) => "read-write",
                    (true, false) => "read",
                    _ => "write",
                };
                nodes.extend([f.id.to_string(), s.id.to_string()]);
                let sa = addr(s.id.as_str());
                let trace = format!("rhizo:edge={}->{} access={access}", f.id, s.id);
                match k::ty(s) {
                    BUCKET => {
                        let prefix = e.props.get("prefix").and_then(Value::as_str).unwrap_or("");
                        let trace = if prefix.is_empty() { trace } else { format!("{trace} prefix={prefix}") };
                        for (on, role, suffix) in [(read, OBJECT_VIEWER, "read"), (write, OBJECT_CREATOR, "write")] {
                            if !on {
                                continue;
                            }
                            let mut items = vec![
                                a("bucket", format!("{}.name", m(s))),
                                a("role", q(role)),
                                a("member", principal.clone()),
                            ];
                            if !prefix.is_empty() {
                                items.extend([
                                    Item::Blank,
                                    block(
                                        "condition",
                                        vec![
                                            a("title", q(&format!("prefix {prefix}"))),
                                            a(
                                                "expression",
                                                format!(
                                                    "\"resource.name.startsWith(\\\"projects/_/buckets/${{{}.name}}/objects/{}\\\")\"",
                                                    m(s),
                                                    // A CEL string literal first, then HCL: an HCL escape must not close it.
                                                    super::esc(&prefix.replace('\\', "\\\\").replace('"', "\\\""))
                                                ),
                                            ),
                                        ],
                                    ),
                                ]);
                            }
                            groups.push(res(
                                "google_storage_bucket_iam_member",
                                format!("{fa}_{sa}_{suffix}"),
                                trace.clone(),
                                items,
                            ));
                        }
                    }
                    TABLE => {
                        let role = match access {
                            "read" => q("roles/datastore.viewer"),
                            "write" => format!("google_project_iam_custom_role.{sa}_writer.id"),
                            _ => q("roles/datastore.user"),
                        };
                        if access == "write" {
                            groups.push(res(
                                "google_project_iam_custom_role",
                                format!("{sa}_writer"),
                                format!("rhizo:node={}: write without read, which no predefined role grants", s.id),
                                vec![
                                    a("project", "local.project"),
                                    a(
                                        "role_id",
                                        q(&format!("{}Writer", super::pascal(&format!("{}_{}", self.name, s.id)))),
                                    ),
                                    a("title", q(&format!("{} writer", s.label))),
                                    a(
                                        "permissions",
                                        list(
                                            [
                                                "datastore.databases.getMetadata",
                                                "datastore.entities.create",
                                                "datastore.entities.delete",
                                                "datastore.entities.update",
                                            ]
                                            .map(q),
                                        ),
                                    ),
                                ],
                            ));
                        }
                        groups.push(res(
                            "google_project_iam_member",
                            format!("{fa}_{sa}"),
                            format!("{trace} (Firestore has no database-level binding: a condition names the database)"),
                            vec![
                                a("project", "local.project"),
                                a("role", role),
                                a("member", principal.clone()),
                                Item::Blank,
                                block(
                                    "condition",
                                    vec![
                                        a("title", q(&format!("database {}", self.base(s)))),
                                        a(
                                            "expression",
                                            format!(
                                                "\"resource.name == \\\"projects/${{local.project}}/databases/${{google_firestore_database.{sa}.name}}\\\"\""
                                            ),
                                        ),
                                    ],
                                ),
                            ],
                        ));
                    }
                    QUEUE | TOPIC => {
                        if write {
                            groups.push(res(
                                "google_pubsub_topic_iam_member",
                                format!("{fa}_{sa}_publish"),
                                trace.clone(),
                                vec![
                                    a("project", "local.project"),
                                    a("topic", format!("{}.id", m(s))),
                                    a("role", q(PUBLISHER)),
                                    a("member", principal.clone()),
                                ],
                            ));
                        }
                        if read && k::ty(s) == QUEUE {
                            for (i, sub) in self.queue_subs(s).iter().enumerate() {
                                let owner = if i == 0 {
                                    m(s)
                                } else {
                                    self.links_to(s, Link::Subscribe).get(i - 1).map_or_else(|| m(s), |(_, t)| m(t))
                                };
                                groups.push(res(
                                    "google_pubsub_subscription_iam_member",
                                    format!("{fa}_{}", addr(sub)),
                                    trace.clone(),
                                    vec![
                                        a("project", "local.project"),
                                        a("subscription", q(sub)),
                                        a("role", q(SUBSCRIBER)),
                                        a("member", principal.clone()),
                                        Item::Blank,
                                        a("depends_on", format!("[{owner}]")),
                                    ],
                                ));
                            }
                        }
                    }
                    POSTGRES => {
                        let condition = || {
                            block(
                                "condition",
                                vec![
                                    a("title", q(&format!("instance {}", self.base(s)))),
                                    a(
                                        "expression",
                                        format!(
                                            "\"resource.name == \\\"projects/${{local.project}}/instances/${{{}.instance_name}}\\\"\"",
                                            m(s)
                                        ),
                                    ),
                                ],
                            )
                        };
                        for (role, what) in
                            [("roles/cloudsql.client", "client"), ("roles/cloudsql.instanceUser", "login")]
                        {
                            groups.push(res(
                                "google_project_iam_member",
                                format!("{fa}_{sa}_{what}"),
                                format!(
                                    "{trace} (Cloud SQL has no instance-level binding: a condition names the instance; the database role is created in SQL, task T-{})",
                                    f.id
                                ),
                                vec![
                                    a("project", "local.project"),
                                    a("role", q(role)),
                                    a("member", principal.clone()),
                                    Item::Blank,
                                    condition(),
                                ],
                            ));
                        }
                    }
                    _ => {}
                }
            }
        }
        let mut invoked: Vec<(&Node, String, String)> = Vec::new();
        for f in self.pushed() {
            let edges: Vec<String> = self
                .links_to(f, Link::Trigger)
                .iter()
                .chain(&self.links_to(f, Link::Subscribe))
                .map(|(_, s)| format!("{}->{}", s.id, f.id))
                .collect();
            invoked.push((f, PUSH.to_string(), format!("rhizo:edge={} (Pub/Sub pushes as {PUSH})", edges.join(" "))));
        }
        for api in self.of(HTTP_API) {
            let mut seen = BTreeSet::new();
            for (_, f) in self.links_from(api, Link::Route) {
                if seen.insert(f.id.clone()) {
                    invoked.push((
                        f,
                        Self::gateway_key(api),
                        format!("rhizo:edge={}->{} (the gateway calls it)", api.id, f.id),
                    ));
                }
            }
        }
        for (f, who, trace) in invoked {
            nodes.insert(f.id.to_string());
            groups.push(res(
                "google_cloud_run_v2_service_iam_member",
                format!("{}_{}", addr(f.id.as_str()), addr(&who)),
                trace,
                vec![
                    a("project", "local.project"),
                    a("location", "local.region"),
                    a("name", format!("google_cloudfunctions2_function.{}.name", addr(f.id.as_str()))),
                    a("role", q(INVOKER)),
                    a("member", member(&who)),
                ],
            ));
        }
        (groups, nodes.into_iter().collect())
    }

