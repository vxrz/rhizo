fn build(src: &str, name: &str) -> Bundle {
    let loaded = rhizo_lang::load(src, rhizo_lang::Syntax::Kdl);
    assert!(!loaded.has_errors(), "{:?}", loaded.diagnostics);
    compile(&loaded.document, &Kits::builtin(), name, src)
        .unwrap_or_else(|fs| panic!("{:#?}", fs.into_iter().map(|f| f.diagnostic.message).collect::<Vec<_>>()))
}

fn text<'a>(b: &'a Bundle, path: &str) -> &'a str {
    &b.files.get(path).unwrap_or_else(|| panic!("no {path} in {:?}", b.files.keys())).contents
}

/// The block that starts with `head` (a line of its own), up to its closing brace.
fn block<'a>(file: &'a str, head: &str) -> &'a str {
    let start = file.find(head).unwrap_or_else(|| panic!("no `{head}` in\n{file}"));
    let end = file[start..].find("\n}\n").map_or(file.len(), |e| start + e + 3);
    &file[start..end]
}

#[test]
fn bundle_layout_manifest_and_determinism() {
    let a = build(PLAYGROUND, "shop.rhizo");
    let infra: Vec<&str> = a.files.keys().map(String::as_str).filter(|p| p.starts_with("infra/")).collect();
    assert_eq!(
        infra,
        [
            "infra/production/encryption.tofu",
            "infra/production/iam.tf",
            "infra/production/main.tf",
            "infra/production/network.tf",
            "infra/production/outputs.tf",
            "infra/production/providers.tf",
            "infra/production/variables.tf",
            "infra/production/versions.tf",
        ]
    );
    assert_eq!(a.files, build(PLAYGROUND, "shop.rhizo").files, "same input, same bytes");
    let listed = manifest_files(&a.files[MANIFEST].contents);
    for path in infra {
        let (_, hash) = listed.iter().find(|(p, _)| p == path).expect("listed in the manifest");
        assert_eq!(*hash, sha256(a.files[path].contents.as_bytes()));
    }
    assert_eq!(a.files["infra/production/main.tf"].nodes, ["api", "net", "orders-db", "orders-fn", "receipts"]);
    for f in a.files.keys().filter(|p| p.starts_with("infra/")) {
        assert!(text(&a, f).starts_with("# @generated by rhizo "), "{f}");
        assert!(!text(&a, f).contains("\n\n\n"), "{f}");
    }
}

