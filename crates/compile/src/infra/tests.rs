/// The kitchen sink written with cloud-neutral types: renamed props, and
/// settings only AWS has in an `aws` block.
fn neutral(src: &str) -> String {
    let mut s = src.to_string();
    for (neutral, aws) in rhizo_kit::infra::NEUTRAL {
        s = s.replace(&format!("type={aws}"), &format!("type={neutral}"));
    }
    for (aws, neutral) in [
        ("multi-az=", "high-availability="),
        ("hash-key=", "partition-key="),
        ("range-key=", "sort-key="),
        ("range-key-type=", "sort-key-type="),
        ("fifo=", "ordered="),
        ("visibility-timeout-s=", "lock-timeout-s="),
        ("dlq=", "dead-letter="),
    ] {
        s = s.replace(aws, neutral);
    }
    s.replace(" architecture=\"x86_64\" {\n", " {\n                    aws architecture=\"x86_64\"\n").replace(
        "database=\"reports\" instance-class=\"db.t4g.small\"\n",
        "database=\"reports\" {\n                    aws instance-class=\"db.t4g.small\"\n                }\n",
    )
}

#[test]
fn neutral_types_compile_like_their_aws_types() {
    let aws = SINK.replace("database=\"reports\"\n", "database=\"reports\" instance-class=\"db.t4g.small\"\n");
    let neutral = neutral(&aws);
    assert!(!neutral.contains("type=aws.") && neutral.contains("aws instance-class"), "{neutral}");
    let (a, n) = (build(&aws, "sink.rhizo"), build(&neutral, "sink.rhizo"));
    let infra = |b: &Bundle| -> Vec<(String, String)> {
        b.files.iter().filter(|(p, _)| p.starts_with("infra/")).map(|(p, f)| (p.clone(), f.contents.clone())).collect()
    };
    assert_eq!(infra(&a), infra(&n));
    assert!(text(&a, "infra/staging/main.tf").contains("db.t4g.small"), "the aws block reached the module");
    let tasks = |b: &Bundle| -> Vec<String> {
        let v: serde_json::Value = serde_json::from_str(text(b, TASKS)).unwrap();
        v["tasks"]
            .as_array()
            .unwrap()
            .iter()
            .map(|t| format!("{} {} {}", t["id"], t["kind"], t["depends_on"]))
            .collect()
    };
    assert_eq!(tasks(&a), tasks(&n));
}

